# text edits that carry the marks
# ---------------------------------------------------------------------------------------------------------------------
class Marked:
    """A text and the positions of its marks (sorted by position, ties in document order). A mark is (kind 0 start / 1 end, tag index)."""

    def __init__(self, text: str, marks):
        marks = sorted(marks, key=lambda m: m[0])        # stable sort
        self.text = text
        self.pos = [m[0] for m in marks]
        self.kind = [m[1] for m in marks]
        self.idx = [m[2] for m in marks]

    def edit(self, edits):
        """edits: sorted, non-overlapping (start, end, replacement). A start mark inside a replaced span moves after the replacement, an end mark before it."""
        if not edits:
            return
        out = []
        P = self.pos
        K = self.kind
        newpos = list(P)
        nm = len(P)
        j = 0
        last = 0
        olen = 0
        for (s, e, r) in edits:
            while j < nm and P[j] <= s:
                newpos[j] = olen + (P[j] - last)
                j += 1
            out.append(self.text[last:s])
            olen += s - last
            out.append(r)
            while j < nm and P[j] < e:
                newpos[j] = olen + (len(r) if K[j] == 0 else 0)
                j += 1
            olen += len(r)
            last = e
        while j < nm:
            newpos[j] = olen + (P[j] - last)
            j += 1
        out.append(self.text[last:])
        self.text = ''.join(out)
        self.pos = newpos

    def sub(self, pattern, repl):
        edits = []
        for m in pattern.finditer(self.text):
            r = repl(m) if callable(repl) else repl
            if r != m.group(0):
                edits.append((m.start(), m.end(), r))
        self.edit(edits)


_ENT = re.compile(r'&(#\d+|\w+);')
_CTRL = re.compile(r'[\x00-\x08\x0b-\x1f\x7f]')
_INVIS = re.compile('[­​﻿]')
_HY1 = re.compile(r'(?<=\w)[¬⸗-]\n\s*(?=[a-zà-ÿſ])')
_HY2 = re.compile(r'(?<=\w)¬\n\s*(?=\w)')
_SP = re.compile(r'[ \t\f\v]+')
_NL = re.compile(r'\n\s*')
_NL3 = re.compile(r'\n{3,}')
_LBNO = re.compile(r'\u0001\s*')
_TCP = re.compile('∣')
_CR = re.compile('\r')


def clean_marked(m: Marked, tei: bool = True) -> None:
    """ner2_layer_extract.tei_body_text tail (tei=True) + clean_text, step for step, on a Marked text."""
    if tei:
        m.sub(_TCP, '')
        m.sub(_LBNO, '')
    if '&' in m.text and _ENT.search(m.text):
        m.sub(_ENT, lambda x: html.unescape(x.group(0)))
    m.sub(_CR, '')
    m.sub(_INVIS, '')
    m.sub(_CTRL, ' ')
    m.sub(_HY1, '')
    m.sub(_HY2, '')
    m.sub(_SP, ' ')
    m.sub(_NL, '\n')
    m.sub(_NL3, '\n\n')
    t = m.text
    s = len(t) - len(t.lstrip())
    e = len(t.rstrip())
    edits = []
    if s:
        edits.append((0, s, ''))
    if e < len(t):
        edits.append((e, len(t), ''))
    m.edit(edits)


# drop capitals: same pattern and rules as ner2_layer_extract.repair_dropcaps, returning the edits (the deleted spaces)
ALPHA = 'A-Za-zÀ-ÖØ-öø-ÿſÆŒæœ'
LEGIT_SINGLE = {'en': set('aAIOoy'), 'la': set('aAeEoOiI&'), 'it': set('aAeEoOiIéÉèÈàÀ'), 'es': set('aAeEoOyYuU'),
                'fr': set('aAyYàÀôÔ'), 'de': set('aAiIoO')}
DROPCAP_PAT = re.compile(r"(?<![\w'’\-̀-ͯ])([^\W\d_]) ([a-zà-ÿſ]{2,})(?![\ẁ-ͯ]|\w*['’])")


def fold(s: str) -> str:
    s = s.replace('ſ', 's')
    s = unicodedata.normalize('NFD', s)
    return ''.join(c for c in s if unicodedata.category(c) != 'Mn').lower()


def doc_vocab(text: str):
    t = DROPCAP_PAT.sub(' ', text)
    return Counter(fold(w) for w in re.findall(rf'[{ALPHA}]+', t))


def dropcap_edits(text: str, lang: str, vocab) -> list:
    legit = LEGIT_SINGLE.get(lang, set('aAeEoOiI')) | set('Jj')
    edits = []
    for m in DROPCAP_PAT.finditer(text):
        letter, rest = m.group(1), m.group(2)
        if letter in legit or (ord(letter) > 0x7f and letter not in 'ſ'):
            continue
        joined = fold(letter + rest)
        known = vocab.get(joined, 0) > 0
        if letter.islower() and letter != 'ſ':
            if not known:
                continue
        elif not (known or vocab.get(fold(rest), 0) == 0):
            continue
        edits.append((m.end(1), m.start(2), ''))
    return edits


def finish_marked(m: Marked, tags: list, lang: str, repair: bool = True, tei: bool = True):
    """Clean-up + drop-capital repair. Returns (text, n_dropcap, tag rows with char_start / char_end; empty ranges dropped)."""
    clean_marked(m, tei)
    n_rep = 0
    if repair:
        ed = dropcap_edits(m.text, lang, doc_vocab(m.text))
        n_rep = len(ed)
        m.edit(ed)
    text = m.text
    start, end = {}, {}
    for p, k, i in zip(m.pos, m.kind, m.idx):
        (start if k == 0 else end)[i] = p
    rows = []
    for i, t in enumerate(tags):
        if i not in start or i not in end:
            continue
        s, e = start[i], end[i]
        while s < e and text[s].isspace():
            s += 1
        while e > s and text[e - 1].isspace():
            e -= 1
        if e <= s:
            continue
        rows.append({**t, 'char_start': s, 'char_end': e})
    return text, n_rep, rows


def extract_tei(root, lang: str, repair: bool = True, name_tags=None, norm_newlines: bool = True):
    """TEI root -> dict(text, tags, place, ex, dropped_tags, n_dropcap), or None when there is no body."""
    got = tei_body(root, name_tags, norm_newlines)
    if got is None:
        return None
    raw, ctx = got
    m = Marked(raw, ctx.marks)
    text, n_rep, rows = finish_marked(m, ctx.tags, lang, repair)
    return {'text': text, 'tags': rows, 'place': ctx.place, 'ex': dict(ctx.ex), 'dropped_tags': dict(ctx.dropped_tags), 'n_dropcap': n_rep}


def extract_plain(raw: str, lang: str, repair: bool = True, spans=None):
    """Plain text through the same clean-up. spans: optional [(start, end, tag, type, ref)] on the raw text -> tag rows on the final text."""
    tags, marks = [], []
    for i, (s, e, tag, ty, ref) in enumerate(spans or []):
        tags.append({'tag': tag, 'type': ty, 'ref': ref, 'cert': '', 'nested': False})
        marks.append((s, 0, i))
        marks.append((e, 1, i))
    m = Marked(raw, marks)
    text, n_rep, rows = finish_marked(m, tags, lang, repair, tei=False)
    return {'text': text, 'tags': rows, 'n_dropcap': n_rep}


# ---------------------------------------------------------------------------------------------------------------------
# 8-word shingles (folded words), one in eight kept, as 64-bit hashes (vectorised)
# ---------------------------------------------------------------------------------------------------------------------
SHINGLE = 8
SAMPLE_MOD = 4
_W = re.compile(r'\w+', re.U)
_FOLD_CACHE: dict = {}
_P = np.uint64(0x9E3779B97F4A7C15)


def _wid(w: str) -> int:
    v = _FOLD_CACHE.get(w)
    if v is None:
        f = fold(w).encode('utf-8')
        v = zlib.crc32(f) | (zlib.adler32(f) << 32)
        if len(_FOLD_CACHE) < 3_000_000:
            _FOLD_CACHE[w] = v
    return v


def word_ids(text: str) -> np.ndarray:
    ws = _W.findall(text)
    return np.fromiter((_wid(w) for w in ws), dtype=np.uint64, count=len(ws))


def shingles_of_ids(ids: np.ndarray) -> np.ndarray:
    """Sampled shingle hashes (uint64, unique) of a word-id array."""
    n = len(ids) - SHINGLE + 1
    if n <= 0:
        return np.zeros(0, dtype=np.uint64)
    h = np.zeros(n, dtype=np.uint64)
    with np.errstate(over='ignore'):
        for k in range(SHINGLE):
            h = (h * _P) ^ ids[k:k + n]
            h ^= h >> np.uint64(29)
    h = h[(h % np.uint64(SAMPLE_MOD)) == 0]
    return np.unique(h)


def shingle_hashes(text: str) -> np.ndarray:
    return shingles_of_ids(word_ids(text))


def fingerprint(ids: np.ndarray) -> int:
    """Hash of the whole folded word sequence (exact duplicates, also for texts too short to have sampled shingles)."""
    return (zlib.crc32(ids.tobytes()) << 20) ^ len(ids)
