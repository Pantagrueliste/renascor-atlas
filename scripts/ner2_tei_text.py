"""TEI editions for the NER layer: running text of a TEI document with the character ranges of the editors' name tags (pure logic, no I/O).

Same reading as ``ner2_layer_extract.tei_body_text`` (diplomatic: printed form kept, regularisation and editorial additions left out, end-of-line hyphens joined),
then the same clean-up (``clean_text``) and drop-capital repair, but every step is done on a text that carries the tag boundaries, so the character
ranges of the tags stay exact in the final text.

What is read: the ``body`` only (as in the first pass). What is left out of it, and counted per category (non-space characters):

    note_editorial   notes by the editors (type editorial / footnote / regest / entity / ..., or with a ``resp`` other than the author)
    note_other       notes of an unknown kind (the first pass left out every note). Kept: marginal notes, address, signature (the early modern text)
    apparatus        ``rdg`` readings (the ``lem`` is read)
    div_editorial    divisions typed translation / regest / commentary / register / index / ...
    head_editorial   titles added by the editors (``resp`` or type editorial)
    standoff         spanGrp and ``span`` with from / to (stand-off annotation)
    diplomatic       what the first pass left out too: reg, expan, corr, supplied, del, surplus, ex, fw, figure, pb, gap, imprimatur

The teiHeader, front and back are not read (counted by the caller from the whole file).

Editor tags recorded (``CORE_NAME_TAGS`` + ``EXTRA_NAME_TAGS``): placeName, settlement, country, region, geogName, geogFeat, bloc, district, persName,
orgName, name, rs, and the project tags found by the survey. A tag inside a left-out element has no range (counted in ``dropped_tags``).
"""
from __future__ import annotations

import html
import re
import unicodedata
import zlib
from collections import Counter

import numpy as np

CORE_NAME_TAGS = frozenset(('placeName', 'settlement', 'country', 'region', 'geogName', 'geogFeat', 'bloc', 'district', 'persName', 'orgName', 'name', 'rs'))
EXTRA_NAME_TAGS: frozenset = frozenset(('pubPlace',))      # imprint place on title pages inside the body (found by the survey of the editions)
PLACE_TAGS = frozenset(('placeName', 'settlement', 'country', 'region', 'geogName', 'geogFeat', 'bloc', 'district', 'pubPlace'))

# what the first pass left out (ner2_layer_extract.SKIP_TAGS), minus note (classified here), minus rdg (apparatus)
DIPLOMATIC_SKIP = frozenset(('figure', 'pb', 'fw', 'gap', 'del', 'corr', 'reg', 'expan', 'supplied', 'imprimatur', 'surplus', 'ex'))
BLOCK_BREAK = frozenset(('p', 'l', 'lg', 'head', 'item', 'salute', 'dateline', 'closer', 'signed', 'trailer', 'label', 'speaker', 'stage', 'div', 'sp'))
BLOCK_END = frozenset(('p', 'lg', 'head', 'item', 'sp'))

EDITORIAL_NOTE_TYPES = frozenset((
    'editorial', 'footnote', 'regest', 'entity', 'comment', 'commentary', 'annotation', 'linguisticnote', 'trad', 'translation', 'critical', 'textcrit',
    'apparatus', 'source', 'lemma', 'misc', 'author', 'gloss', 'paleo', 'selection', 'start', 'end', 'editor', 'ed', 'explicatory', 'explanation', 'kommentar',
    'anmerkung', 'sachkommentar', 'textkritik', 'variant', 'addressee', 'intro', 'summary', 'regeste', 'transcription', 'bibl', 'citation'))
KEEP_NOTE_TYPES = frozenset(('margin', 'marginal', 'marginalia', 'margin_left', 'margin_right', 'marginleft', 'marginright', 'marge', 'sidenote', 'address',
                             'adresse', 'signature', 'authorial', 'original', 'orig', 'main_right', 'main_left'))
AUTHOR_RESP = frozenset(('author', '#author', 'auctor'))
EDITORIAL_DIV_TYPES = frozenset((
    'translation', 'regest', 'regeste', 'summary', 'commentary', 'kommentar', 'register', 'index', 'editorial', 'apparatus', 'notes', 'glossary', 'glossar',
    'bibliography', 'bibliographie', 'introduction', 'einleitung', 'edition', 'paratext', 'indexlocorum', 'indexnominum', 'verzeichnis', 'traducao', 'traduccion'))
EDITORIAL_HEAD_TYPES = frozenset(('editorial', 'editor', 'supplied', 'regest', 'summary', 'ed'))
_SRC_NL = re.compile(r'(?<![-¬⸗])[ \t\r]*\n[ \t\r\n]*')      # a line feed after a hyphen stays: clean_text joins the word
EDITORIAL_HEAD_TEXT = re.compile(r'^\s*(main text of|text of (the )?(letter|attachment)|decoded text)\b', re.I)       # headings generated by the Suriano edition
PLACE_TYPED = re.compile(r'^(place|location|loc|settlement|region|country|geog\w*|toponym|address)$', re.I)


def local(el):
    t = el.tag
    if not isinstance(t, str):
        return None
    return t.rsplit('}', 1)[-1]


def _low(v):
    return (v or '').strip().lower()


def note_kind(el) -> str:
    """'keep' (marginal note, address, signature: early modern text), 'editorial' or 'other' (unknown kind: left out)."""
    ty = _low(el.get('type')) or _low(el.get('subtype'))
    resp = _low(el.get('resp'))
    if ty in EDITORIAL_NOTE_TYPES:
        return 'editorial'
    if resp and resp not in AUTHOR_RESP:
        return 'editorial'
    if ty in KEEP_NOTE_TYPES:
        return 'keep'
    place = _low(el.get('place'))
    if not ty and place and ('margin' in place or place in ('left', 'right', 'foot', 'inline', 'above', 'below', 'interlinear')):
        return 'keep'
    if ty and ('margin' in ty or ty.startswith('marge')):
        return 'keep'
    return 'other'


def div_excluded(el) -> bool:
    return _low(el.get('type')) in EDITORIAL_DIV_TYPES or _low(el.get('subtype')) in EDITORIAL_DIV_TYPES


def head_excluded(el) -> bool:
    ty = _low(el.get('type'))
    resp = _low(el.get('resp'))
    return ty in EDITORIAL_HEAD_TYPES or (bool(resp) and resp not in AUTHOR_RESP)


def nonspace(s: str) -> int:
    return len(''.join(s.split()))


class Ctx:
    def __init__(self, name_tags=None, norm_newlines=True):
        self.norm_newlines = norm_newlines
        self.buf: list[str] = []
        self.n = 0
        self.marks: list[tuple[int, int, int]] = []        # (position in the raw text, 0 start / 1 end, tag index)
        self.tags: list[dict] = []
        self.ex = Counter()
        self.dropped_tags = Counter()
        self.name_tags = name_tags or (CORE_NAME_TAGS | EXTRA_NAME_TAGS)
        self.place = False
        self.open_tags = 0
        self.last_nl = False

    def put(self, s):
        if s:
            self.buf.append(s)
            self.n += len(s)
            self.last_nl = s.endswith('\n')

    def text_node(self, s):
        """Text of the file between elements: a line feed there is the layout of the XML file (one word per line in pretty-printed TEI), not a line break of the
        source; breaks come from <lb/> and from the block elements."""
        if s and self.norm_newlines and '\n' in s:
            s = _SRC_NL.sub(' ', s)
        self.put(s)


def _skip(el, ctx: Ctx, cat: str):
    ctx.ex[cat] += nonspace(''.join(el.itertext()))
    for d in el.iter():
        t = local(d)
        if t in ctx.name_tags:
            ctx.dropped_tags[t] += 1


def walk(el, ctx: Ctx):
    tag = local(el)
    if tag is None:
        return
    if tag in PLACE_TAGS:
        ctx.place = True
    if tag == 'note':
        k = note_kind(el)
        if k != 'keep':
            _skip(el, ctx, 'note_editorial' if k == 'editorial' else 'note_other')
            return
    elif tag == 'rdg':
        _skip(el, ctx, 'apparatus')
        return
    elif tag in ('spanGrp', 'annotationBlock') or (tag == 'span' and (el.get('from') or el.get('to'))):
        _skip(el, ctx, 'standoff')
        return
    elif tag in DIPLOMATIC_SKIP:
        _skip(el, ctx, 'diplomatic')
        return
    elif tag == 'seg' and ('translation' in _low(el.get('decls')) or _low(el.get('type')) == 'translation'):
        _skip(el, ctx, 'div_editorial')                  # editors' translation of a passage (Casebooks)
        return
    elif tag == 'div' and div_excluded(el):
        _skip(el, ctx, 'div_editorial')
        return
    elif tag in ('head', 'titlePart', 'title') and (head_excluded(el) or (tag == 'head' and EDITORIAL_HEAD_TEXT.match(''.join(el.itertext())))):
        _skip(el, ctx, 'head_editorial')
        return
    if tag == 'lb':
        ctx.put('\u0001' if (el.get('break') == 'no' or el.get('rend') == '¬') else '\n')
        return
    if tag == 'g' and (el.get('ref') or '').endswith('EOLhyphen'):
        return
    if tag in BLOCK_BREAK and ctx.buf and not ctx.last_nl:
        ctx.put('\n')
    idx = None
    if tag in ctx.name_tags:
        ty = el.get('type') or el.get('role') or el.get('subtype') or ''
        if tag in ('rs', 'name') and PLACE_TYPED.match(ty):
            ctx.place = True
        ctx.tags.append({'tag': tag, 'type': ty, 'ref': el.get('ref') or el.get('key') or el.get('corresp') or '', 'cert': el.get('cert') or '',
                         'nested': ctx.open_tags > 0})
        idx = len(ctx.tags) - 1
        ctx.marks.append((ctx.n, 0, idx))
        ctx.open_tags += 1
    ctx.text_node(el.text)
    for c in el:
        walk(c, ctx)
        if c.tail:
            ctx.text_node(c.tail)
    if tag in BLOCK_END:
        ctx.put('\n')
    if idx is not None:
        ctx.open_tags -= 1
        ctx.marks.append((ctx.n, 1, idx))


def tei_body(root, name_tags=None, norm_newlines=True):
    """Raw reading of the body with the tag boundaries. Returns (raw_text, ctx), or None when the file has no body."""
    body = None
    for el in root.iter():
        if local(el) == 'body':
            body = el
            break
    if body is None:
        return None
    ctx = Ctx(name_tags, norm_newlines)
    walk(body, ctx)
    return ''.join(ctx.buf), ctx


