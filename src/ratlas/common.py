_GND = r'([0-9]+-[0-9Xx]|[0-9]{6,10}[0-9Xx]?)'
_RX: list[tuple[str, re.Pattern]] = [
    ('gnd', re.compile(r'(?:d-nb\.info/gnd/|lobid\.org/gnd/|portal\.dnb\.de/opac[^ ]*?idn=|\(DE-588\)|^(?:gnd|pnd)[:_/ ]+)' + _GND, re.I)),
    ('viaf', re.compile(r'(?:viaf\.org/viaf/|^viaf[:_/ ]+)(\d+)', re.I)),
    ('wikidata', re.compile(r'(?:wikidata\.org/(?:wiki|entity)/(?:Special:EntityData/)?|^wd:|^wikidata[:_/ ]+|^)(Q\d+)$', re.I)),
    ('geonames', re.compile(r'(?:geonames\.org/(?:maps/[^ ]*?geonameId=)?|^(?:gn|geonames|geonameid)[:_/ ]+)(\d+)', re.I)),
    ('tgn', re.compile(r'(?:vocab\.getty\.edu/(?:page/)?tgn/|getty\.edu/[^ ]*?tgn[^ ]*?subjectid=|^tgn[:_/ ]+)(\d+)', re.I)),
    ('ulan', re.compile(r'(?:vocab\.getty\.edu/(?:page/)?ulan/|getty\.edu/[^ ]*?ulan[^ ]*?subjectid=|^ulan[:_/ ]+)(\d+)', re.I)),
    ('pleiades', re.compile(r'(?:pleiades\.stoa\.org/places/|^pleiades[:_/ ]+)(\d+)', re.I)),
    ('hls', re.compile(r'(?:hls-dhs-dss\.ch/(?:de|fr|it|rm|en)/articles/|hls-dhs-dss\.ch/textes/[a-z]/[A-Z]|^hls[:_/ ]+)(\d+)', re.I)),
]
_RX_OTHER: list[tuple[str, re.Pattern]] = [
    ('isni', re.compile(r'(?:isni\.org/isni/|^isni[:_/ ]+)(\d{4} ?\d{4} ?\d{4} ?\d{3}[\dXx])', re.I)),
    ('loc', re.compile(r'(?:id\.loc\.gov/authorities/(?:names|subjects)/|^loc[:_/ ]+)([a-z]{1,2}\d+)', re.I)),
    ('dbpedia', re.compile(r'dbpedia\.org/(?:resource|page)/(.+)$', re.I)),
    ('cerl', re.compile(r'data\.cerl\.org/thesaurus/(\w+)', re.I)),
    ('bnf', re.compile(r'(?:ark:/12148/|data\.bnf\.fr/(?:ark:/12148/)?)(cb\w+)', re.I)),
    ('deutsche-biographie', re.compile(r'deutsche-biographie\.de/(?:pnd)?(\w+?)(?:\.html)?(?:[?#].*)?$', re.I)),
    ('whg', re.compile(r'whgazetteer\.org/places/(\d+)', re.I)),
    ('odnb', re.compile(r'(?:ref:odnb/|odnb[:_/ ]+)(\d+)', re.I)),
    ('ppn', re.compile(r'^ppn[:_/ ]+(\w+)$', re.I)),
]
_HASH_AUTH = re.compile(r'#(?:tgn|tng|gnd|pnd|ulan|viaf|wikidata|geonames)[_:]\d', re.I)
_WIKIPEDIA = re.compile(r'^https?://([a-z]{2,3})\.(?:m\.)?wikipedia\.org/wiki/([^?#]+)', re.I)
_WS_SCHEMES = {'gnd', 'viaf', 'wikidata', 'geonames', 'tgn', 'ulan', 'pleiades', 'hls'}


def classify_token(tok: str) -> tuple[str, str]:
    """Classify ONE reference token (no whitespace).

    Returns (scheme, id):
      ('gnd', '118540238'), ('wikidata', 'Q90'), ('geonames', '2988507'), ... for the AUTH_KEYS schemes;
      ('other', 'isni:0000000121251078') for other known authorities and ('other', 'url:https://...') for any
      other external http(s) URL;
      ('local', 'frag') for '#frag', 'file.xml#frag', 'prefix:id' or a bare id (the id as written, without '#');
      ('none', '') for an empty or '#' token.
    """
    tok = tok.strip()
    if not tok or tok == '#':
        return ('none', '')
    if tok.startswith('#') and _HASH_AUTH.match(tok):      # '#TGN_7001242' (HAB registers; 'TNG' is a recurrent typo)
        tok = tok[1:]
        if tok[:3].upper() == 'TNG':
            tok = 'TGN' + tok[3:]
    for scheme, rx in _RX:
        m = rx.search(tok)
        if m:
            return (scheme, m.group(1).upper() if scheme in ('gnd', 'wikidata') else m.group(1))
    for scheme, rx in _RX_OTHER:
        m = rx.search(tok)
        if m:
            return ('other', f'{scheme}:{m.group(1).replace(" ", "")}')
    m = _WIKIPEDIA.match(tok)
    if m:
        return ('other', f'wikipedia:{m.group(1).lower()}:{m.group(2)}')
    if re.match(r'https?://', tok, re.I):
        return ('other', 'url:' + tok[:200])
    if tok.startswith('#'):
        return ('local', tok[1:])
    if '#' in tok:
        return ('local', tok.rsplit('#', 1)[1])
    return ('local', tok)


def parse_auth(values: Iterable[str], into: Optional[dict] = None) -> dict:
    """Build an auth dict from reference strings (space-separated tokens allowed). First id per scheme wins;
    further ids of a scheme go to ``other`` as 'scheme:id'."""
    a = into if into is not None else empty_auth()
    for v in values:
        if not v:
            continue
        for tok in v.split():
            scheme, ident = classify_token(tok)
            if scheme in _WS_SCHEMES:
                if not a.get(scheme):
                    a[scheme] = ident
                elif a[scheme] != ident:
                    x = f'{scheme}:{ident}'
                    if x not in a['other']:
                        a['other'].append(x)
            elif scheme == 'other' and ident not in a['other']:
                a['other'].append(ident)
    return a


def merge_auth(a: dict, b: Optional[dict]) -> dict:
    """Merge b into a copy of a (a wins on conflicts; b's conflicting ids go to other)."""
    out = {k: a.get(k) for k in AUTH_KEYS} | {'other': list(a.get('other') or [])}
    if not b:
        return out
    for k in AUTH_KEYS:
        if b.get(k) and not out[k]:
            out[k] = b[k]
        elif b.get(k) and out[k] != b[k] and f'{k}:{b[k]}' not in out['other']:
            out['other'].append(f'{k}:{b[k]}')
    for x in b.get('other') or []:
        if x not in out['other']:
            out['other'].append(x)
    return out


def idno_to_token(el) -> str:
    """Turn an <idno type="GND">118540238</idno> (or an idno holding a URL) into a classifiable token."""
    txt = norm(''.join(el.itertext()))
    typ = (el.get('type') or '').strip().lower()
    if not txt:
        return ''
    txt = re.sub(r'(geonames\.org/)\s+', r'\1', txt)         # 'http://geonames.org/ 2955439' (HAB registers)
    if typ in ('gnd', 'viaf', 'wikidata', 'geonames', 'tgn', 'ulan', 'pleiades', 'hls', 'isni', 'loc', 'cerl') \
            and not re.match(r'https?://', txt):
        return f'{typ}:{txt}'
    if typ in ('wikipedia',) and txt.startswith('http'):
        return txt
    return txt


