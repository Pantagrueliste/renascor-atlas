@dataclass
class FileRecord:
    """One XML file (or archive member) of the harvest, as inventoried by scan.py."""
    path: str                      # relative to raw_root(); '!' separates archive and member
    coll: str                      # scan collection key
    sha1: str = ''
    dup: bool = False
    bytes: int = 0
    c: dict = field(default_factory=dict)        # 'zone|tag' -> count (zones hdr/txt/reg)
    refs: dict = field(default_factory=dict)     # 'zone|tag|attr|class' -> count
    dates: list = field(default_factory=list)
    langs: dict = field(default_factory=dict)
    words: int = 0
    scan_error: Optional[str] = None
    data: Optional[bytes] = None   # filled by iter_with_data()

    @property
    def archive(self) -> str:
        return self.path.split('!', 1)[0]

    @property
    def member(self) -> Optional[str]:
        return self.path.split('!', 1)[1] if '!' in self.path else None

    @property
    def name(self) -> str:
        return PurePosixPath(self.member or self.path).name

    @property
    def stem(self) -> str:
        n = self.name
        for ext in ('.gz', '.xml', '.tei'):
            if n.lower().endswith(ext):
                n = n[: -len(ext)]
        return n

    def count(self, *keys: str) -> int:
        """Sum of scan counts for 'zone|tag' keys, e.g. rec.count('txt|persName', 'txt|placeName')."""
        return sum(self.c.get(k, 0) for k in keys)

    def read(self) -> bytes:
        return self.data if self.data is not None else read_raw(self.path)

    @classmethod
    def from_scan(cls, r: dict) -> 'FileRecord':
        return cls(path=r['path'], coll=r['coll'], sha1=r.get('sha1', ''), dup=bool(r.get('dup')),
                   bytes=r.get('bytes', 0), c=r.get('c', {}), refs=r.get('refs', {}), dates=r.get('dates', []),
                   langs=r.get('langs', {}), words=r.get('words', 0), scan_error=r.get('error'))


def is_forbidden(path: str) -> bool:
    low = path.lower()
    return any(t in low for t in FORBIDDEN_PATH_TOKENS)


def matches(rec_path: str, rec_coll: str, selectors: Iterable[str]) -> bool:
    """A selector matches when it equals the scan coll or is a raw string prefix of the path."""
    return any(rec_coll == s or rec_path.startswith(s) for s in selectors)


def iter_scan(selectors: Optional[Iterable[str]] = None, include_dups: bool = False) -> Iterator[FileRecord]:
    """Stream FileRecords of scan.jsonl.gz whose coll or path matches one of ``selectors`` (None = all).

    Skips duplicate content (dup=true) unless include_dups, records without sha1 (unreadable or too big) and the
    FORBIDDEN_PATH_TOKENS collections.
    """
    sels = list(selectors) if selectors is not None else None
    for sp in scan_files():
        with gzip.open(sp, 'rt', encoding='utf-8') as fh:
            for line in fh:
                if sels is not None and not any(s in line for s in sels):   # cheap pre-filter before json.loads
                    continue
                r = json.loads(line)
                if 'sha1' not in r:
                    continue
                if r.get('dup') and not include_dups:
                    continue
                if sels is not None and not matches(r['path'], r['coll'], sels):
                    continue
                if is_forbidden(r['path']):
                    continue
                yield FileRecord.from_scan(r)


def iter_collection_files(selectors: Iterable[str], include_dups: bool = False) -> list[FileRecord]:
    """All (non-duplicate) XML records of a collection, sorted by path."""
    return sorted(iter_scan(selectors, include_dups), key=lambda r: r.path)


def read_raw(path: str) -> bytes:
    """Bytes of a raw file or of an archive member ('archive!member'), for xml, zip, tar(.gz) and .gz.

    Reading a member of a .tar.gz is sequential: for many members use iter_with_data().
    """
    root = raw_root()
    if '!' not in path:
        p = root / path
        if p.name.lower().endswith('.gz') and not p.name.lower().endswith('.tar.gz'):
            return gzip.open(p).read()
        return p.read_bytes()
    arch, member = path.split('!', 1)
    low = arch.lower()
    if low.endswith('.zip'):
        with zipfile.ZipFile(root / arch) as z:
            return z.read(member)
    with tarfile.open(root / arch) as tf:
        f = tf.extractfile(member)
        if f is None:
            raise FileNotFoundError(path)
        return f.read()


def list_members(archive: str) -> list[str]:
    """File names inside a zip or tar archive (relative path of the archive under raw_root())."""
    p = raw_root() / archive
    if archive.lower().endswith('.zip'):
        with zipfile.ZipFile(p) as z:
            return [i.filename for i in z.infolist() if not i.is_dir()]
    with tarfile.open(p) as tf:
        return [m.name for m in tf if m.isfile()]


def iter_with_data(records: Iterable[FileRecord]) -> Iterator[FileRecord]:
    """Yield records with ``.data`` filled, opening each archive once (zip random access, tar sequential)."""
    recs = list(records)
    plain = [r for r in recs if '!' not in r.path]
    by_arch: dict[str, list[FileRecord]] = {}
    for r in recs:
        if '!' in r.path:
            by_arch.setdefault(r.archive, []).append(r)
    root = raw_root()
    for r in plain:
        r.data = read_raw(r.path)
        yield r
    for arch, rs in by_arch.items():
        low = arch.lower()
        if low.endswith('.zip'):
            with zipfile.ZipFile(root / arch) as z:
                for r in rs:
                    r.data = z.read(r.member)
                    yield r
        else:
            want = {r.member: r for r in rs}
            with tarfile.open(root / arch) as tf:
                for m in tf:
                    r = want.get(m.name) if m.isfile() else None
                    if r is not None:
                        r.data = tf.extractfile(m).read()
                        yield r


