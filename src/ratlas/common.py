def _alias_candidates(ident: str) -> list[str]:
    c = [ident]
    if ':' in ident:
        c.append(ident.split(':', 1)[1])
    if '/' in ident:
        c.append(ident.rsplit('/', 1)[1])
    return c


def resolve_refs(refs: dict, kind: str, ctx: Context, *registers: Register
                 ) -> tuple[Optional[str], Optional[bool], dict, Optional[Entity]]:
    """Resolve the @ref/@key/@corresp/@sameAs of one tag.

    Returns (local_key, in_register, auth, entity).
      * authority urls/ids in the tokens go to ``auth``;
      * local tokens ('#id', 'file.xml#id', 'prefix:id', 'id') are looked up in ``registers`` (file-local first,
        then ctx.shared); a hit gives local_key and its entity's ids are merged into auth;
      * a miss gives local_key None, unless ctx.opaque_keys: then '<slug>:<id>' with in_register False.
    """
    auth = empty_auth()
    regs = list(registers) + [ctx.shared]
    hit: Optional[Entity] = None
    opaque: Optional[str] = None
    fallback_hit: Optional[Entity] = None
    for attr in REF_ATTRS:
        v = refs.get(attr)
        if not v:
            continue
        for tok in v.split():
            scheme, ident = classify_token(tok)
            if scheme in _WS_SCHEMES or scheme == 'other':
                parse_auth([tok], into=auth)
            elif scheme == 'local' and hit is None:
                for cand in _alias_candidates(ident):
                    for r in regs:
                        e = r.lookup(cand)
                        if e is not None:
                            if e.kind == kind:
                                hit = e
                            elif fallback_hit is None:
                                fallback_hit = e
                            break
                    if hit is not None:
                        break
                if hit is None and opaque is None and ident:
                    opaque = ident
    hit = hit or fallback_hit
    if hit is not None:
        return hit.local_key, True, merge_auth(auth, hit.auth), hit
    if opaque and ctx.opaque_keys:
        return make_key(ctx.slug, opaque), False, auth, None
    return None, None, auth, None


_HYPH = re.compile(r'(?<=\w)[-\u00ad\u2010\u2011\u2012] (?=[a-zß-ÿ])')       # 'Lon- dres', 'Po- linville' (line-break hyphens)
_TRAIL = re.compile(r'[\s,;:·]+$')


def _clean_surface(s: str) -> str:
    """v2 normalisation of a surface: line-break hyphen joined, trailing punctuation dropped (a final abbreviation dot is kept
    when the token is short: 'St.', 'Frf.'; a dot after a long word goes: 'Hagam.' -> 'Hagam')."""
    if not s:
        return s
    s = _HYPH.sub('', s)
    t = _TRAIL.sub('', s)
    if t.endswith('.') and len(t.rsplit(' ', 1)[-1]) > 4:
        t = t[:-1].rstrip(' ,;:·')
    return t.strip() or s.strip()


def own_auth(refs: dict) -> dict:
    """Authority ids written on the tag itself (no register lookup)."""
    a = empty_auth()
    for attr in REF_ATTRS:
        v = refs.get(attr)
        if v:
            parse_auth([v], into=a)
    return a


def drop_inherited(m: Mention, ent: Entity, refs: dict) -> Mention:
    """Metonymy / tag-type mismatch (audit point 7): the tag keeps its own kind and does not inherit the ids of an
    entry of another kind. The register link is kept as ``<entry key>~<kind>`` (not an entry: in_register False)."""
    own = own_auth(refs)
    new = empty_auth()
    for k in AUTH_KEYS:
        v = (m.auth or {}).get(k)
        if v and (v == own.get(k) or v != (ent.auth or {}).get(k)):
            new[k] = v
    ent_other = set((ent.auth or {}).get('other') or [])
    new['other'] = [x for x in (m.auth or {}).get('other') or [] if x in own['other'] or x not in ent_other]
    m.auth = new
    m.local_key = f'{ent.local_key}~{m.kind}'
    m.in_register = False
    if m.kind == 'person' and not m.person_class:
        m.person_class = 'metonym'
    return m


def build_mentions(root, rec: FileRecord, ctx: Context, *, local: Optional[Register] = None,
                   date: Optional[DocDate] = None, hits: Optional[list[Hit]] = None,
                   counters: Optional[Counter] = None,
                   adjust: Optional[Callable[[Mention, Hit], Optional[Mention]]] = None) -> list[Mention]:
    """Hits -> Mention rows (dates, licence, context policy, resolution). Used by GenericTEI.extract.

    ``adjust(mention, hit)`` may edit a mention (e.g. read a GeoNames id from a bare @ref, change the role) and
    return it, or return None to drop it.

    v2: the refined zone (``classify.zone_class_of_hit``) and the editor's ``@cert`` are set before ``adjust``; a tag
    whose register entry is of another kind keeps its own kind and inherits no id (``drop_inherited``); a tag with no
    letter and no reference at all is dropped."""
    if date is None:
        date = resolve_doc_date(root, rec, filename_dates=ctx.filename_dates, default_years=ctx.default_years)
    dlang = doc_language(root)
    if hits is None:
        hits = scan_mentions(root, type_map=ctx.type_map, want_context=ctx.want_context, doc_lang=dlang,
                             counters=counters)
    doc_id = doc_id_of(root, rec)
    regs = [local] if local is not None and len(local) else []
    year = best_year(date.year_from, date.year_to)
    inp = period_overlap(date.year_from, date.year_to)
    out = []
    for h in hits:
        if not h.refs and not classify._has_letter(h.surface or ''):
            continue
        lk, inreg, auth, ent = resolve_refs(h.refs, h.kind, ctx, *regs)
        cert = ((h.el.get('cert') or '').strip().lower() if h.el is not None else '') or None
        h.surface = _clean_surface(h.surface)
        m = Mention(
            coll_slug=ctx.slug, renascor_id=ctx.renascor_id, source_path=rec.path, doc_id=doc_id,
            doc_year=year, doc_year_from=date.year_from, doc_year_to=date.year_to, date_source=date.source,
            in_period=inp, kind=h.kind, tag=h.tag, role=h.role, zone=h.zone, surface=h.surface,
            ref_raw=' '.join(h.refs.values()) or None, local_key=lk, in_register=inreg, auth=auth,
            context=h.context if ctx.want_context else None, lang=h.lang, licence=ctx.licence, tier=ctx.tier,
            zone_class=classify.zone_class_of_hit(h, ctx.options), cert=cert if cert in ('high', 'medium', 'low') else None)
        if adjust is not None:
            m = adjust(m, h)
            if m is None:
                continue
        if ent is not None and m.local_key == ent.local_key and ent.kind != m.kind:
            drop_inherited(m, ent, h.refs)
        out.append(m)
    return out


# ======================================================================================================================
# 9. writer
# ======================================================================================================================
class Writer:
    """Streams mentions to out/<slug>/mentions.parquet; entities are deduplicated by local_key and written at
    close() with n_mentions; stats.json summarises the run. Enforces the licence rules (no context for T3)."""

    def __init__(self, out_dir: Path, slug: str, licence: str, tier: str, batch: int = 50000):
        self.dir = Path(out_dir)
        self.dir.mkdir(parents=True, exist_ok=True)
        self.slug, self.licence, self.tier, self.batch = slug, licence, tier, batch
        self._mw = pq.ParquetWriter(self.dir / 'mentions.parquet', MENTION_SCHEMA, compression='zstd')
        self._rows: list[dict] = []
        self.entities: dict[str, Entity] = {}
        self.mention_count: Counter = Counter()
        self.t0 = time.time()
        self.s = Counter()
        self.by_kind: Counter = Counter()
        self.by_role: Counter = Counter()
        self.by_zone: Counter = Counter()
        self.by_kind_role: Counter = Counter()
        self.by_zone_class: Counter = Counter()
        self.by_class: Counter = Counter()
        self.by_excluded: Counter = Counter()      # 'kind|reason' -> n
        self.n_excluded = 0
        self.date_sources: Counter = Counter()
        self.unresolved: Counter = Counter()
        self.errors: list[dict] = []
        self.invalid: Counter = Counter()
        self.dup_entities = 0
        self.files = 0

    def note_file(self, path: str, error: Optional[str] = None):
        self.files += 1
        if error:
            self.s['file_errors'] += 1
            if len(self.errors) < 50:
                self.errors.append({'path': path, 'error': error[:300]})

    def add(self, mentions: Iterable[Mention], entities: Iterable[Entity] = ()):
        for e in entities:
            if e.local_key in self.entities:
                self.dup_entities += 1
                continue
            e.licence = e.licence or self.licence
            e.tier = e.tier or self.tier
            self.entities[e.local_key] = e
        for m in mentions:
            self._add_mention(m)
        if len(self._rows) >= self.batch:
            self._flush()

    def _add_mention(self, m: Mention):
        classify.finalize(m, self.entities.get(m.local_key) if m.local_key else None)
        if m.zone_class not in ZONE_CLASSES:
            self.invalid['zone_class:' + str(m.zone_class)] += 1
        if m.person_class is not None and m.person_class not in PERSON_CLASSES:
            self.invalid['person_class:' + str(m.person_class)] += 1
        self.by_zone_class[f'{m.kind}|{m.zone_class}'] += 1
        self.by_class[f'{m.kind}|{m.person_class}'] += 1
        if m.excluded:
            self.n_excluded += 1
            for r in (m.excluded_reason or '').split(';'):
                self.by_excluded[f'{m.kind}|{r}'] += 1
        m.coll_slug = self.slug
        m.licence = m.licence or self.licence
        m.tier = m.tier or self.tier
        if m.tier not in ('T1', 'T2'):
            m.context = None
        elif m.context and len(m.context) > 120:
            m.context = m.context[:120]
        if m.kind not in KINDS:
            self.invalid['kind:' + str(m.kind)] += 1
        if m.zone not in ZONES:
            self.invalid['zone:' + str(m.zone)] += 1
        if m.date_source is not None and m.date_source not in DATE_SOURCES:
            self.invalid['date_source:' + str(m.date_source)] += 1
        if m.role not in ROLES:
            self.s['nonstandard_role'] += 1
        s = self.s
        s['mentions'] += 1
        self.by_kind[m.kind] += 1
        self.by_role[m.role] += 1
        self.by_zone[m.zone] += 1
        self.by_kind_role[f'{m.kind}|{m.role}'] += 1
        if m.local_key:
            s['resolved'] += 1
            self.mention_count[m.local_key] += 1
            if m.in_register:
                s['in_register'] += 1
        elif m.ref_raw:
            s['unresolved_with_ref'] += 1
            if not (m.auth and not auth_is_empty(m.auth)):
                self.unresolved[m.ref_raw[:80]] += 1
        else:
            s['no_ref'] += 1
        if not auth_is_empty(m.auth):
            s['with_auth'] += 1
        if m.in_period is None:
            s['undated'] += 1
        else:
            s['dated'] += 1
            s['in_period'] += bool(m.in_period)
        if m.date_source:
            self.date_sources[m.date_source] += 1
        if m.context:
            s['with_context'] += 1
        self._rows.append(m.to_row())

    def _flush(self):
        if self._rows:
            self._mw.write_table(pa.Table.from_pylist(self._rows, schema=MENTION_SCHEMA))
            self._rows = []

    def close(self) -> dict:
        self._flush()
        self._mw.close()
        rows = []
        for k, e in self.entities.items():
            e.n_mentions = self.mention_count.get(k, 0)
            e.person_class = classify.entity_class(e)
            rows.append(e.to_row())
        pq.write_table(pa.Table.from_pylist(rows, schema=ENTITY_SCHEMA), self.dir / 'entities.parquet',
                             compression='zstd')
        s = self.s
        n = s['mentions'] or 1
        ents = list(self.entities.values())
        ne = len(ents) or 1
        stats = {
            'slug': self.slug, 'licence': self.licence, 'tier': self.tier,
            'files_read': self.files, 'file_errors': s['file_errors'], 'errors': self.errors,
            'mentions': s['mentions'],
            'mentions_by_kind': dict(self.by_kind), 'mentions_by_role': dict(self.by_role),
            'mentions_by_zone': dict(self.by_zone), 'mentions_by_kind_role': dict(self.by_kind_role),
            'mentions_by_zone_class': dict(self.by_zone_class), 'mentions_by_class': dict(self.by_class),
            'mentions_excluded': self.n_excluded, 'mentions_excluded_by_reason': dict(self.by_excluded),
            'resolved_share': round(s['resolved'] / n, 4),
            'in_register_share': round(s['in_register'] / n, 4),
            'auth_share': round(s['with_auth'] / n, 4),
            'with_ref_unresolved': s['unresolved_with_ref'], 'no_ref': s['no_ref'],
            'dated': s['dated'], 'undated': s['undated'],
            'in_period_share': round(s['in_period'] / s['dated'], 4) if s['dated'] else None,
            'in_period_share_all': round(s['in_period'] / n, 4),
            'date_sources': dict(self.date_sources),
            'context_rows': s['with_context'],
            'nonstandard_role_rows': s['nonstandard_role'], 'invalid_values': dict(self.invalid),
            'entities': len(ents), 'duplicate_entities_dropped': self.dup_entities,
            'entities_by_kind': dict(Counter(e.kind for e in ents)),
            'entities_with_auth_share': round(sum(not auth_is_empty(e.auth) for e in ents) / ne, 4),
            'entities_with_coords_share': round(sum(e.lat is not None for e in ents) / ne, 4),
            'entities_never_mentioned': sum(1 for e in ents if not e.n_mentions),
            'top_unresolved_refs': self.unresolved.most_common(20),
            'seconds': round(time.time() - self.t0, 1),
        }
        (self.dir / 'stats.json').write_text(json.dumps(stats, ensure_ascii=False, indent=1))
        return stats
