def make_key(slug: str, ident: str, doc_id: Optional[str] = None) -> str:
    """'<slug>:<id>' for a shared register, '<slug>:<doc_id>#<id>' for a register inside one document."""
    return f'{slug}:{doc_id}#{ident}' if doc_id else f'{slug}:{ident}'


class Register:
    """Entities of one scope plus an alias index (xml:id and any extra alias) -> local_key."""

    def __init__(self):
        self.entities: dict[str, Entity] = {}
        self.index: dict[str, str] = {}

    def add(self, ent: Entity, aliases: Iterable[str] = ()):
        self.entities[ent.local_key] = ent
        for a in aliases:
            if a:
                self.index.setdefault(a, ent.local_key)

    def lookup(self, token_id: str) -> Optional[Entity]:
        k = self.index.get(token_id)
        return self.entities.get(k) if k else None

    def __len__(self):
        return len(self.entities)


@dataclass
class Context:
    """Everything an extractor needs; built once per run by the runner from the module constants."""
    slug: str
    licence: str
    tier: str
    renascor_ids: list = field(default_factory=list)
    default_years: Optional[tuple] = None        # (from, to) used when no date is found (date_source 'collection')
    filename_dates: bool = False                 # try a year in the file name when the header has none
    opaque_keys: bool = False                    # set local_key='<slug>:<id>' even when the id is not in a register
    type_map: dict = field(default_factory=dict) # extra rs/name @type -> kind
    options: dict = field(default_factory=dict)  # free module options
