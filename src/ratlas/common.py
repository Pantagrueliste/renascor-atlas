# 3. XML parsing and text helpers
# ======================================================================================================================
_WS = re.compile(r'\s+')


def norm(s: Optional[str]) -> str:
    """Whitespace-normalised text (runs of whitespace incl. NBSP become one space; stripped)."""
    return _WS.sub(' ', s).strip() if s else ''


def ln(tag) -> Optional[str]:
    """Local name of an lxml tag (None for comments and processing instructions)."""
    if not isinstance(tag, str):
        return None
    return tag.rsplit('}', 1)[-1] if '}' in tag else tag


def parse_xml(data: bytes):
    """Parse bytes into an lxml root; recover from errors, huge trees allowed, no network, no entity expansion.

    Returns None if nothing could be parsed. Nothing in the XML is ever executed.
    """
    parser = etree.XMLParser(recover=True, huge_tree=True, resolve_entities=False, no_network=True,
                             load_dtd=False, remove_comments=True, remove_pis=True)
    try:
        root = etree.fromstring(data, parser)
    except etree.XMLSyntaxError:
        return None
    return root


def children(el, *names: str):
    """Direct children whose local name is in names."""
    return [c for c in el if ln(c.tag) in names]


def child(el, *names: str):
    for c in el:
        if ln(c.tag) in names:
            return c
    return None


# <choice> alternatives dropped in favour of the diplomatic reading. 'reg' also yields to <abbr>: a triple
# <abbr>d</abbr><expan>de</expan><reg>De</reg> otherwise gave the garbled surface 'dDe' (postscriptum).
_ALT_OF = {'expan': ('abbr',), 'corr': ('sic',), 'reg': ('orig', 'abbr')}


def _skipped_alt(el) -> bool:
    """True for <expan>/<corr>/<reg> that have an <abbr>/<sic>/<orig> sibling in a <choice>: we keep the
    diplomatic reading as written in the source and drop the editorial alternative."""
    alt = _ALT_OF.get(ln(el.tag))
    if alt is None:
        return False
    p = el.getparent()
    return p is not None and ln(p.tag) == 'choice' and any(ln(s.tag) in alt for s in p)


def surface_text(el) -> str:
    """Whitespace-normalised text of an element (diplomatic reading, editorial alternatives dropped)."""
    out: list[str] = []

    def rec(e):
        if e.text:
            out.append(e.text)
        for c in e:
            # v2: an editorial <note> nested in a tag is not part of the name (sozinianische: 'Rittershusio Der gelehrte Jurist ...')
            if isinstance(c.tag, str) and not _skipped_alt(c) and not (c is not el and ln(c.tag) == 'note'):
                rec(c)
            if c.tail:
                out.append(c.tail)

    rec(el)
    return norm(''.join(out))


def name_text(el) -> str:
    """Name of a register element. With name-part children (forename, surname...) the parts are space-joined."""
    parts = [c for c in el if ln(c.tag) in ('forename', 'surname', 'roleName', 'nameLink', 'addName', 'genName')]
    if parts:
        return norm(' '.join(surface_text(c) for c in parts))
    return surface_text(el)


