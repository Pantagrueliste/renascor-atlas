CAND_TAGS = {'persName': 'person', 'placeName': 'place', 'orgName': 'org', 'geogName': 'place',
             'settlement': 'place', 'country': 'place', 'region': 'place', 'district': 'place', 'bloc': 'place'}
TYPED_TAGS = ('rs', 'name')
TYPE_MAP = {
    **{k: 'person' for k in ('person', 'persons', 'pers', 'persname', 'personne', 'personnage', 'people',
                             'individual', 'figure', 'character', 'person_name', 'personal', 'persoon')},
    **{k: 'place' for k in ('place', 'places', 'plac', 'placename', 'loc', 'location', 'geog', 'geogname',
                            'settlement', 'city', 'country', 'region', 'toponym', 'lieu', 'ort', 'locus',
                            'topo', 'toponyme', 'plaats', 'geo', 'geographic')},
    **{k: 'org' for k in ('org', 'orgname', 'organisation', 'organization', 'institution', 'corporate',
                          'corporation', 'collective', 'organisme')},
}
REG_ANCESTORS = {'listPerson', 'listPlace', 'listOrg', 'listEvent', 'standOff', 'person', 'personGrp', 'org',
                 'place', 'event'}
HDR_SKIP_ANCESTORS = {'respStmt', 'editionStmt', 'revisionDesc', 'encodingDesc', 'funder', 'sponsor', 'principal',
                      'availability', 'licence', 'change', 'editor', 'publicationStmt'}
REF_ATTRS = ('ref', 'key', 'corresp', 'sameAs')


def kind_of(name: str, el, type_map: Optional[dict] = None) -> tuple[Optional[str], str]:
    """(kind, tag label) for an element, or (None, name) when it is not an entity candidate."""
    if name in CAND_TAGS:
        return CAND_TAGS[name], name
    if name in TYPED_TAGS:
        tm = TYPE_MAP if not type_map else {**TYPE_MAP, **type_map}
        for attr in ('type', 'role'):
            raw = (el.get(attr) or '').strip().lower()
            for tok in raw.split():
                if tok in tm:
                    return tm[tok], f'{name}@{tok}'
        return None, name
    return None, name


def role_for(names: list[str], els: list, kind: str, zone: str) -> str:
    """Default role from the ancestors: correspAction (sender/addressee/sent_from/sent_to), titleStmt author
    (header), <signed> (signer), <dateline> place (sent_from), cast lists (cast), else 'mention'."""
    for n, e in zip(reversed(names), reversed(els)):
        if n == 'correspAction':
            t = (e.get('type') or '').lower()
            if t.startswith('sen') or t in ('from', 'origin'):
                return 'sent_from' if kind == 'place' else 'sender'
            if t.startswith(('rec', 'del')) or t in ('to', 'dest', 'destination'):
                return 'sent_to' if kind == 'place' else 'addressee'
            return 'mention'
        if n == 'author' and zone == 'hdr' and kind == 'person':
            return 'author'
        if n == 'signed' and kind != 'place':
            return 'signer'
        if n == 'dateline' and kind == 'place':
            return 'sent_from'
        if n in ('castItem', 'castList') and kind != 'place':
            return 'cast'
    return 'mention'


@dataclass
class Hit:
    kind: str
    tag: str            # label: 'persName', 'rs@place', ...
    name: str           # element local name
    surface: str
    zone: str           # 'txt' | 'hdr'
    role: str
    refs: dict          # attr -> raw value (non-empty only)
    lang: Optional[str]
    context: Optional[str]
    el: object
    ancestors: tuple    # local names of the ancestors, outermost first


def scan_mentions(root, *, type_map: Optional[dict] = None, want_context: bool = False,
                  doc_lang: Optional[str] = None, role_fn: Optional[Callable] = None,
                  counters: Optional[Counter] = None, skip_ancestors: Iterable[str] = (),
                  nested_inner: bool = False) -> list[Hit]:
    """Every editor-tagged person/place/org in the text and header of a TEI tree (register entries excluded).

    Candidates: persName, placeName, orgName, geogName, settlement/country/region/district/bloc, and rs/name
    whose @type (or @role) maps to person/place/org via TYPE_MAP (+ ``type_map``). Untyped rs/name are counted in
    ``counters['untyped_rs_name']`` and skipped. A same-kind tag nested in another candidate is skipped when it
    has no reference of its own (or the same one). Register containers (listPerson, standOff, person, place...)
    and editorial header parts (respStmt, editionStmt, publicationStmt, revisionDesc...) are skipped.
    Text is read diplomatically (abbr/sic/orig kept; expan/corr/reg dropped when an alternative exists).
    ``nested_inner`` (v2): when a same-kind tag without reference sits inside another one, keep the INNER tag and drop the outer
    (Old Bailey: 'Michael Hair , and Mary his Wife' holds two persName).
    """
    counters = counters if counters is not None else Counter()
    skip_anc = set(skip_ancestors)
    names: list[str] = []
    els: list = []
    langs: list = []
    frames: list = []       # per stack level: None or candidate frame
    open_cands: list = []   # open candidate frames
    parts: list[str] = []
    pos = 0
    skip_el = None
    in_header = 0
    out: list[dict] = []
    for ev, el in etree.iterwalk(root, events=('start', 'end')):
        n = ln(el.tag)
        if n is None:
            continue
        if ev == 'start':
            names.append(n)
            els.append(el)
            langs.append(el.get(XML_LANG) or (langs[-1] if langs else doc_lang))
            frame = None
            if n == 'teiHeader':
                in_header += 1
            kind, label = kind_of(n, el, type_map)
            if kind is None and n in TYPED_TAGS:
                counters['untyped_rs_name'] += 1
            if kind is not None:
                anc = names[:-1]
                sa = set(anc)
                zone = 'hdr' if in_header else 'txt'
                skip = bool(sa & REG_ANCESTORS) or bool(sa & skip_anc)
                if not skip and zone == 'hdr':
                    hs = sa & HDR_SKIP_ANCESTORS
                    if 'sourceDesc' in sa:
                        hs = hs - {'publicationStmt'}
                    skip = bool(hs)
                refs = {a: v.strip() for a in REF_ATTRS if (v := el.get(a)) and v.strip() and v.strip() != '#'}
                if not skip and open_cands:
                    par = open_cands[-1]
                    if par['kind'] == kind and (not refs or refs == par['refs']):
                        if nested_inner and not par['refs']:
                            par['skip'] = True
                            par['role'] = None
                        else:
                            skip = True
                frame = {'kind': kind, 'label': label, 'name': n, 'refs': refs, 'zone': zone, 'skip': skip,
                         'start': pos, 'end': pos, 'el': el, 'anc': tuple(anc), 'lang': langs[-1],
                         'role': None if skip else (role_fn or role_for)(list(anc), list(els[:-1]), kind, zone)}
                open_cands.append(frame)
            frames.append(frame)
            if skip_el is None and _skipped_alt(el):
                skip_el = el
            if in_header and want_context:      # header elements are block-like: keep their text apart in contexts
                parts.append(' ')
                pos += 1
                if frame is not None:
                    frame['start'] = pos
            if el.text and skip_el is None:
                parts.append(el.text)
                pos += len(el.text)
        else:
            frame = frames.pop()
            if frame is not None:
                frame['end'] = pos
                open_cands.pop()
                if not frame['skip']:
                    out.append(frame)
            if n == 'teiHeader':
                in_header -= 1
            if skip_el is el:
                skip_el = None
            if in_header and want_context and n != 'teiHeader':
                parts.append(' ')
                pos += 1
            if el.tail and skip_el is None:
                parts.append(el.tail)
                pos += len(el.tail)
            names.pop()
            els.pop()
            langs.pop()
    buf = ''.join(parts) if want_context else ''
    hits: list[Hit] = []
    for f in out:
        surf = surface_text(f['el'])
        ctx = None
        if want_context:
            ctx = make_context(buf, f['start'], f['end'], surf)
        hits.append(Hit(kind=f['kind'], tag=f['label'], name=f['name'], surface=surf, zone=f['zone'],
                        role=f['role'], refs=f['refs'], lang=f['lang'], context=ctx, el=f['el'],
                        ancestors=f['anc']))
    return hits


def make_context(buf: str, start: int, end: int, surface: str, limit: int = 120) -> str:
    """Text around a mention, whitespace-normalised, at most ``limit`` chars, surface included."""
    if len(surface) >= limit:
        return surface[:limit]
    budget = limit - len(surface)
    left = norm(buf[max(0, start - 4 * budget): start])
    right = norm(buf[end: end + 4 * budget])
    lb = min(len(left), budget // 2 + max(0, budget // 2 - len(right)))
    rb = min(len(right), budget - lb)
    lb = min(len(left), budget - rb)
    s = (left[len(left) - lb:] if lb else '') + (' ' if lb and not surface.startswith(' ') else '') + surface
    s += (' ' if rb else '') + right[:rb]
    return norm(s)[:limit]


def corresp_roles(root) -> list[dict]:
    """Sender/addressee/places declared in correspDesc: [{'role', 'kind', 'surface', 'refs'}...]."""
    out = []
    for h in scan_mentions(root):
        if h.role in ('sender', 'addressee', 'sent_from', 'sent_to'):
            out.append({'role': h.role, 'kind': h.kind, 'surface': h.surface, 'refs': h.refs})
    return out


def doc_language(root) -> Optional[str]:
    lang = root.get(XML_LANG)
    if lang:
        return lang
    for el in root.iter():
        n = ln(el.tag)
        if n == 'text' and el.get(XML_LANG):
            return el.get(XML_LANG)
        if n == 'language' and el.get('ident'):
            return el.get('ident')
    return None


def doc_id_of(root, rec: FileRecord) -> str:
    return root.get(XML_ID) or rec.stem


