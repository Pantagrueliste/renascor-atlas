_YEAR_RX = re.compile(r'(?<![\d.])(-?\d{4})(?!\d)')
_HDR_DATE_SKIP = {'editionStmt', 'revisionDesc', 'encodingDesc', 'respStmt', 'change', 'funder', 'sponsor',
                  'principal', 'availability', 'licence', 'editor'}
_DATE_ATTRS = ('when', 'notBefore', 'notAfter', 'from', 'to', 'when-iso', 'notBefore-iso', 'notAfter-iso',
               'from-iso', 'to-iso', 'when-custom', 'notBefore-custom', 'notAfter-custom')


def _attr_year(v: str) -> Optional[int]:
    m = re.match(r'\s*(-?\d{4})', v or '')
    return int(m.group(1)) if m else None


def date_range(el, lo: int = 1000, hi: int = 2100) -> Optional[tuple[int, int]]:
    """(year_from, year_to) of a <date>/<creation>/<origDate>-like element: attributes first, else 4-digit
    years in the text. None if there is nothing usable."""
    ys = [y for a in _DATE_ATTRS if (y := _attr_year(el.get(a))) is not None]
    if not ys:
        ys = [int(y) for y in _YEAR_RX.findall(surface_text(el))]
    ys = [y for y in ys if lo <= y <= hi]
    return (min(ys), max(ys)) if ys else None


@dataclass
class DocDate:
    year_from: Optional[int] = None
    year_to: Optional[int] = None
    source: Optional[str] = None     # 'header' | 'letter' | 'filename' | 'collection'

    @property
    def known(self) -> bool:
        return self.year_from is not None or self.year_to is not None


def _union(ranges: list[tuple[int, int]], max_span: int = 400) -> Optional[tuple[int, int]]:
    if not ranges:
        return None
    a, b = min(r[0] for r in ranges), max(r[1] for r in ranges)
    if b - a > max_span:
        return ranges[0]
    return (a, b)


def header_dates(root) -> DocDate:
    """Document date from the TEI header (and, failing that, the letter's dateline/opener or docDate).

    Priority: correspAction/date (source 'letter') > creation/origDate/docDate/settingDesc dates (header) >
    dates inside sourceDesc, e.g. imprint (header) > date in opener/dateline or docDate in <text> ('letter').
    The edition's own publication/revision dates (publicationStmt outside sourceDesc, editionStmt, revisionDesc,
    encodingDesc, respStmt) are never used.
    """
    hdr = None
    for el in root.iter():
        if ln(el.tag) == 'teiHeader':
            hdr = el
            break
    letter: list[tuple[int, int]] = []
    primary: list[tuple[int, int]] = []
    source: list[tuple[int, int]] = []
    if hdr is not None:
        stack: list[str] = []
        sent_pref: list[tuple[int, int]] = []
        for ev, el in etree.iterwalk(hdr, events=('start', 'end')):
            n = ln(el.tag)
            if n is None:
                continue
            if ev == 'end':
                stack.pop()
                continue
            stack.append(n)
            if n not in ('date', 'creation', 'origDate', 'docDate', 'imprint') or set(stack) & _HDR_DATE_SKIP:
                continue
            if 'publicationStmt' in stack and 'sourceDesc' not in stack:
                continue
            if n == 'imprint':
                continue
            rg = date_range(el)
            if rg is None:
                continue
            if 'correspAction' in stack:
                (sent_pref if _corresp_type(el) == 'sent' else letter).append(rg)
            elif 'sourceDesc' in stack and not ({'creation', 'origDate', 'docDate', 'settingDesc'} & set(stack)):
                source.append(rg)
            else:
                primary.append(rg)
        letter = sent_pref or letter
    if letter:
        u = _union(letter)
        return DocDate(u[0], u[1], 'letter')
    if primary:
        u = _union(primary)
        return DocDate(u[0], u[1], 'header')
    if source:
        u = _union(source)
        return DocDate(u[0], u[1], 'header')
    # body: first dateline/opener date or docDate (stop early)
    seen = 0
    stack = []
    for ev, el in etree.iterwalk(root, events=('start', 'end')):
        n = ln(el.tag)
        if n is None:
            continue
        if ev == 'end':
            stack.pop()
            continue
        stack.append(n)
        seen += 1
        if seen > 200000:
            break
        if n == 'teiHeader':
            continue
        if n in ('date', 'docDate') and ('dateline' in stack or 'opener' in stack or n == 'docDate') \
                and 'teiHeader' not in stack:
            rg = date_range(el)
            if rg:
                return DocDate(rg[0], rg[1], 'letter')
    return DocDate()


def _corresp_type(el) -> str:
    p = el
    while p is not None:
        if ln(p.tag) == 'correspAction':
            t = (p.get('type') or '').lower()
            return 'sent' if t.startswith('sen') else ('received' if t.startswith(('rec', 'del')) else t)
        p = p.getparent()
    return ''


def year_from_filename(name: str, lo: int = 1450, hi: int = 1750) -> Optional[int]:
    """First plausible 4-digit year in a file name (opt-in: file names often hold unrelated numbers)."""
    for m in re.finditer(r'(?<!\d)(\d{4})(?!\d)', name):
        y = int(m.group(1))
        if lo <= y <= hi:
            return y
    return None


def resolve_doc_date(root, rec: Optional[FileRecord] = None, *, filename_dates: bool = False,
                     default_years: Optional[tuple[int, int]] = None,
                     fallback: Optional[Callable] = None) -> DocDate:
    """Header date, else (optional) module ``fallback(root, rec)``, else filename year, else collection default."""
    d = header_dates(root)
    if d.known:
        return d
    if fallback is not None:
        d2 = fallback(root, rec)
        if d2 is not None and d2.known:
            return d2
    if filename_dates and rec is not None:
        y = year_from_filename(rec.name)
        if y:
            return DocDate(y, y, 'filename')
    if default_years:
        return DocDate(default_years[0], default_years[1], 'collection')
    return DocDate()


